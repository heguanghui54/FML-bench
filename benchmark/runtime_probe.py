"""Harness-owned runtime attribution probe for candidate code changes."""

from __future__ import annotations

import json
import hashlib
import os
import shutil
import subprocess
from pathlib import Path
from typing import Any

from ml_scientist.execution_contracts import (
    build_candidate_activation_contract,
    validate_runtime_markers,
)


PROBE_DIR = ".fml_runtime_probe"
MARKER_RELATIVE_PATH = "results_tmp/runtime_activation.jsonl"


def _git_source(repo: Path, relative: str) -> str:
    completed = subprocess.run(
        ["git", "show", f"HEAD:{relative}"],
        cwd=repo,
        text=True,
        capture_output=True,
        check=False,
    )
    return completed.stdout if completed.returncode == 0 else ""


def candidate_sources(repo: Path, target_files: list[str]) -> tuple[dict[str, str], dict[str, str]]:
    before: dict[str, str] = {}
    after: dict[str, str] = {}
    for relative in target_files:
        path = repo / relative
        before[relative] = _git_source(repo, relative)
        after[relative] = path.read_text(encoding="utf-8") if path.is_file() else ""
    return before, after


def prepare_runtime_probe(
    *,
    repo: Path,
    target_files: list[str],
    baseline_sources: dict[str, str] | None = None,
    run_id: str,
    configuration: dict[str, Any],
) -> dict[str, Any] | None:
    """Create a sitecustomize profiler when the candidate changes target code.

    The profiler is owned by the harness and is not part of the candidate diff.
    Python imports it automatically from PYTHONPATH before the task entrypoint.
    """
    before, after = candidate_sources(repo, target_files)
    if baseline_sources is not None:
        before = {path: baseline_sources.get(path, "") for path in target_files}
    contract = build_candidate_activation_contract(
        before=before,
        after=after,
        run_id=run_id,
        configuration=configuration,
    )
    activation_contract = contract if contract["changed_files"] else None
    probe_dir = repo / PROBE_DIR
    if probe_dir.exists():
        shutil.rmtree(probe_dir)
    probe_dir.mkdir(parents=True)
    (probe_dir / "candidate_activation_contract.json").write_text(
        json.dumps(contract, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    embedded = json.dumps(contract, ensure_ascii=False, sort_keys=True)
    source = f'''# Generated by the FML harness; not candidate-authored code.
import atexit
import hashlib
import json
import multiprocessing
import os
import random
import sys
import time

CONTRACT = json.loads({embedded!r})
# Each top-level Python entrypoint owns its own hook. Forked DataLoader workers
# inherit this PID and therefore fail the owner check; subprocess-launched
# trainers exec a fresh interpreter and correctly become owners themselves.
OWNER_PID = os.getpid()
TARGETS = {{
    (row["path"], row["symbol"]): row
    for row in CONTRACT.get("mandatory_activation_targets", [])
}}
ASSERTION_PATHS = {{row["path"] for row in CONTRACT.get("configuration_assertions", [])}}
ASSERTION_HASHES = {{
    row["path"]: row.get("candidate_file_sha256")
    for row in CONTRACT.get("configuration_assertions", [])
}}
SEEN = set()
REQUIRED = {{(path, symbol, "CALLABLE_ACTIVATION") for path, symbol in TARGETS}}
REQUIRED.update({{(path, "<module>", "CONFIGURATION_ASSERTION") for path in ASSERTION_PATHS}})
ASSERTION_READY = {{}}
for assertion_path, expected_hash in ASSERTION_HASHES.items():
    try:
        with open(assertion_path, "rb") as assertion_handle:
            observed_hash = hashlib.sha256(assertion_handle.read()).hexdigest()
        ASSERTION_READY[assertion_path] = observed_hash == expected_hash
    except OSError:
        ASSERTION_READY[assertion_path] = False

EXPERIMENTAL_SEED = int(os.environ.get("FML_EXPERIMENTAL_SEED", "0"))
DETERMINISM_CORRECTIONS = []
random.seed(EXPERIMENTAL_SEED)
try:
    import numpy as _fml_numpy
    _fml_numpy.random.seed(EXPERIMENTAL_SEED)
except Exception:
    _fml_numpy = None
try:
    import torch as _fml_torch
    _fml_torch.manual_seed(EXPERIMENTAL_SEED)
except Exception:
    _fml_torch = None
CUDA_SEED_ENFORCED = False

def _enforce_deterministic_flags(include_cuda=False):
    global CUDA_SEED_ENFORCED
    if _fml_torch is None:
        return
    # CUDA runtime initialization before DataLoader fork can deadlock or poison
    # child workers. Defer the CUDA seed until a candidate callable is entered;
    # DomainBed has constructed its loaders by that boundary.
    if include_cuda and not CUDA_SEED_ENFORCED:
        if _fml_torch.cuda.is_available():
            _fml_torch.cuda.manual_seed_all(EXPERIMENTAL_SEED)
        CUDA_SEED_ENFORCED = True
    desired_deterministic = os.environ.get("FML_CUDNN_DETERMINISTIC", "1") == "1"
    desired_benchmark = os.environ.get("FML_CUDNN_BENCHMARK", "0") == "1"
    if _fml_torch.backends.cudnn.deterministic != desired_deterministic:
        DETERMINISM_CORRECTIONS.append({{
            "setting": "torch.backends.cudnn.deterministic",
            "observed": _fml_torch.backends.cudnn.deterministic,
            "required": desired_deterministic,
            "timestamp": time.time(),
        }})
        _fml_torch.backends.cudnn.deterministic = desired_deterministic
    if _fml_torch.backends.cudnn.benchmark != desired_benchmark:
        DETERMINISM_CORRECTIONS.append({{
            "setting": "torch.backends.cudnn.benchmark",
            "observed": _fml_torch.backends.cudnn.benchmark,
            "required": desired_benchmark,
            "timestamp": time.time(),
        }})
        _fml_torch.backends.cudnn.benchmark = desired_benchmark
    if not _fml_torch.are_deterministic_algorithms_enabled():
        DETERMINISM_CORRECTIONS.append({{
            "setting": "torch.deterministic_algorithms",
            "observed": False,
            "required": True,
            "timestamp": time.time(),
        }})
        _fml_torch.use_deterministic_algorithms(True)

_enforce_deterministic_flags(include_cuda=False)

def _is_owner_process():
    return (
        os.getpid() == OWNER_PID
        and multiprocessing.current_process().name == "MainProcess"
    )

def _relative(filename):
    normalized = os.path.normpath(filename)
    for path in CONTRACT.get("changed_files", []):
        if normalized.endswith(os.path.normpath(path)):
            return path
    return None

def _write(path, symbol, kind="CALLABLE_ACTIVATION"):
    if not _is_owner_process():
        return
    key = (path, symbol, kind)
    if key in SEEN:
        return
    SEEN.add(key)
    marker_path = os.environ.get("FML_RUNTIME_MARKER_PATH", {MARKER_RELATIVE_PATH!r})
    os.makedirs(os.path.dirname(marker_path) or ".", exist_ok=True)
    row = {{
        "schema_version": "fml-runtime-activation-marker-v1",
        "run_id": CONTRACT["run_id"],
        "candidate_sha256": CONTRACT["candidate_sha256"],
        "configuration_sha256": CONTRACT["configuration_sha256"],
        "path": path,
        "symbol": symbol,
        "kind": kind,
        "timestamp": time.time(),
    }}
    with open(marker_path, "a", encoding="utf-8") as handle:
        handle.write(json.dumps(row, sort_keys=True) + "\\n")
    if REQUIRED.issubset(SEEN):
        sys.setprofile(None)

def _profile(frame, event, arg):
    # DataLoader workers inherit sys.setprofile under Linux fork. They are not
    # candidate executors and profiling every image transform can dominate the
    # benchmark. Disable the hook immediately outside the original entrypoint.
    if not _is_owner_process():
        sys.setprofile(None)
        return None
    if event != "call":
        return _profile
    if (
        not REQUIRED
        and frame.f_globals.get("__name__") == "__main__"
        and frame.f_code.co_name != "<module>"
    ):
        sys.setprofile(None)
        return None
    path = _relative(frame.f_code.co_filename)
    if path is None:
        return _profile
    symbol = getattr(frame.f_code, "co_qualname", None)
    if not symbol:
        # Python 3.10 has no code.co_qualname. Recover the owning class from
        # the bound receiver so contracts using Class.method remain portable.
        receiver = frame.f_locals.get("self")
        owner = type(receiver).__name__ if receiver is not None else None
        symbol = f"{{owner}}.{{frame.f_code.co_name}}" if owner else frame.f_code.co_name
    symbol = symbol.replace(".<locals>.", ".")
    if (path, symbol) not in TARGETS:
        # Static methods have no bound receiver on Python 3.10. Qualify a
        # legacy bare name only when the contract has exactly one matching
        # changed callable in this file; ambiguity deliberately stays invalid.
        matches = [
            target_symbol
            for target_path, target_symbol in TARGETS
            if target_path == path and target_symbol.rsplit(".", 1)[-1] == frame.f_code.co_name
        ]
        if len(matches) == 1:
            symbol = matches[0]
    if (path, symbol) in TARGETS:
        # Entrypoints may assign backend flags after sitecustomize imports.
        # Reassert at the candidate-call boundary, not on every Python call.
        _enforce_deterministic_flags(include_cuda=True)
        _write(path, symbol)
    if path in ASSERTION_PATHS and frame.f_code.co_name == "<module>":
        _enforce_deterministic_flags(include_cuda=True)
        _write(path, "<module>", "CONFIGURATION_ASSERTION")
    return _profile

def _audit(event, args):
    if not _is_owner_process() or event != "open" or not args:
        return
    path = _relative(str(args[0]))
    if path in ASSERTION_PATHS and ASSERTION_READY.get(path):
        _write(path, "<module>", "CONFIGURATION_ASSERTION")

sys.addaudithook(_audit)
sys.setprofile(_profile)

def _finalize_reproducibility():
    if not _is_owner_process():
        sys.setprofile(None)
        return
    _enforce_deterministic_flags(include_cuda=True)
    marker_path = os.environ.get("FML_RUNTIME_REPRODUCIBILITY_PATH", "results_tmp/runtime_reproducibility.jsonl")
    os.makedirs(os.path.dirname(marker_path) or ".", exist_ok=True)
    if _fml_torch is None:
        torch_state = {{"status": "TORCH_UNAVAILABLE"}}
    else:
        torch_state = {{
            "status": "ENFORCED",
            "torch": _fml_torch.__version__,
            "cuda": _fml_torch.version.cuda,
            "cudnn": _fml_torch.backends.cudnn.version(),
            "deterministic_algorithms": _fml_torch.are_deterministic_algorithms_enabled(),
            "cudnn_deterministic": _fml_torch.backends.cudnn.deterministic,
            "cudnn_benchmark": _fml_torch.backends.cudnn.benchmark,
            "torch_initial_seed": _fml_torch.initial_seed(),
        }}
    row = {{
        "schema_version": "fml-runtime-reproducibility-evidence-v1",
        "pid": os.getpid(),
        "argv": sys.argv,
        "experimental_seed": EXPERIMENTAL_SEED,
        "cublas_workspace_config": os.environ.get("CUBLAS_WORKSPACE_CONFIG"),
        "torch_backend": torch_state,
        "determinism_correction_count": len(DETERMINISM_CORRECTIONS),
        "determinism_corrections": DETERMINISM_CORRECTIONS[:100],
        "timestamp": time.time(),
    }}
    with open(marker_path, "a", encoding="utf-8") as handle:
        handle.write(json.dumps(row, sort_keys=True) + "\\n")
    sys.setprofile(None)

atexit.register(_finalize_reproducibility)
'''
    (probe_dir / "sitecustomize.py").write_text(source, encoding="utf-8")
    return activation_contract


def probe_environment_prefix(repo_expression: str = '"$PWD"') -> str:
    return (
        f"PYTHONPATH={repo_expression}/{PROBE_DIR}:${{PYTHONPATH:-}} "
        f"FML_RUNTIME_MARKER_PATH={MARKER_RELATIVE_PATH} "
    )


def load_runtime_markers(repo: Path) -> list[dict[str, Any]]:
    path = repo / MARKER_RELATIVE_PATH
    rows: list[dict[str, Any]] = []
    if not path.is_file():
        return rows
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(row, dict):
            rows.append(row)
    return rows


def finalize_runtime_probe(
    *,
    repo: Path,
    execution_dir: Path,
    contract: dict[str, Any] | None,
    remove_probe: bool = True,
) -> dict[str, Any]:
    runtime_rows: list[dict[str, Any]] = []
    runtime_path = repo / "results_tmp" / "runtime_reproducibility.jsonl"
    if runtime_path.is_file():
        for line in runtime_path.read_text(encoding="utf-8").splitlines():
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if isinstance(row, dict):
                runtime_rows.append(row)
    torch_rows = [
        row for row in runtime_rows
        if (row.get("torch_backend") or {}).get("status") == "ENFORCED"
    ]
    runtime_reproducibility_passed = bool(runtime_rows) and all(
        (row["torch_backend"].get("deterministic_algorithms") is True)
        and (row["torch_backend"].get("cudnn_deterministic") is True)
        and (row["torch_backend"].get("cudnn_benchmark") is False)
        and row.get("cublas_workspace_config") == ":4096:8"
        for row in torch_rows
    )
    if runtime_rows and not torch_rows:
        runtime_reproducibility_passed = True
    observed_torch_initial_seeds = sorted({
        int(row["torch_backend"]["torch_initial_seed"])
        for row in torch_rows
        if row["torch_backend"].get("torch_initial_seed") is not None
    })
    requested_experimental_seeds = sorted({
        int(row["experimental_seed"])
        for row in runtime_rows
        if row.get("experimental_seed") is not None
    })
    task_seed_override_observed = bool(
        observed_torch_initial_seeds
        and requested_experimental_seeds
        and set(observed_torch_initial_seeds) != set(requested_experimental_seeds)
    )
    runtime_evidence_path = execution_dir / "runtime_reproducibility.json"
    runtime_evidence_path.write_text(
        json.dumps(runtime_rows, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    if contract is None:
        result = {
            "schema_version": "fml-runtime-activation-validation-v1",
            "passed": True,
            "status": "NOT_APPLICABLE_UNCHANGED_BASELINE",
            "valid_marker_count": 0,
        }
    else:
        markers = load_runtime_markers(repo)
        result = validate_runtime_markers(contract, markers)
        result["status"] = "PASSED" if result["passed"] else "INVALID_EXECUTION"
        (execution_dir / "candidate_activation_contract.json").write_text(
            json.dumps(contract, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        (execution_dir / "runtime_activation_markers.json").write_text(
            json.dumps(markers, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
    result["runtime_reproducibility_passed"] = runtime_reproducibility_passed
    result["runtime_reproducibility_process_count"] = len(runtime_rows)
    result["runtime_reproducibility_evidence_sha256"] = hashlib.sha256(
        runtime_evidence_path.read_bytes()
    ).hexdigest()
    result["requested_experimental_seeds"] = requested_experimental_seeds
    result["observed_torch_initial_seeds"] = observed_torch_initial_seeds
    result["task_seed_override_observed"] = task_seed_override_observed
    result["seed_interpretation"] = (
        "BENCHMARK_OWNED_TASK_SEED_DISTINCT_FROM_RESEARCH_AGENT_SEED"
        if task_seed_override_observed
        else "TASK_AND_RESEARCH_AGENT_SEED_MATCH_OR_NOT_APPLICABLE"
    )
    if not runtime_reproducibility_passed:
        result["passed"] = False
        result["status"] = "INVALID_REPRODUCIBILITY"
    (execution_dir / "runtime_activation_validation.json").write_text(
        json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    if remove_probe:
        shutil.rmtree(repo / PROBE_DIR, ignore_errors=True)
    return result
